import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {GREAT_SWORD_MOTIONS58,canonicalBone58,greatSwordNames58} from '../src/greatSwordMap58.js';
const base=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(base,'..');
assert.equal(GREAT_SWORD_MOTIONS58.length,7);
assert.equal(new Set(GREAT_SWORD_MOTIONS58.map(x=>x.file)).size,7);
assert.equal(new Set(GREAT_SWORD_MOTIONS58.map(x=>x.key)).size,7);
for(const x of GREAT_SWORD_MOTIONS58){
  const data=fs.readFileSync(path.join(root,'public/animations/great-sword',x.file));
  assert.ok(data.length>100_000,x.file);
  assert.equal(data.toString('utf8',0,18),'Kaydara FBX Binary',x.file);
  assert.ok(data.includes(Buffer.from('mixamorig:RightArm')),x.file+' right arm missing');
  assert.ok(data.includes(Buffer.from('mixamorig:LeftLeg')),x.file+' left leg missing');
  assert.ok(data.includes(Buffer.from('AnimationCurve')),x.file+' animation curves missing');
}
assert.equal(canonicalBone58('mixamorig:Hips'),'hips');
assert.equal(canonicalBone58('mixamorig_RightHand'),'righthand');
assert.equal(canonicalBone58('Model|mixamorigLeftArm'),'leftarm');
const target=['Hips','Spine','Spine1','Spine2','Neck','Head','LeftShoulder','LeftArm','LeftForeArm','LeftHand','RightShoulder','RightArm','RightForeArm','RightHand','LeftUpLeg','LeftLeg','LeftFoot','RightUpLeg','RightLeg','RightFoot'];
const source=target.map(n=>'mixamorig:'+n);
const mapped=greatSwordNames58(target,source);
assert.equal(Object.keys(mapped).length,target.length);
assert.equal(mapped.RightHand,'mixamorig:RightHand');
const controller=fs.readFileSync(path.join(root,'src/rodin54.js'),'utf8');
const loader=fs.readFileSync(path.join(root,'src/greatSword58.js'),'utf8');
const main=fs.readFileSync(path.join(root,'src/main.js'),'utf8');
assert.ok(main.includes('loadGreatSword58(THREE,rodin54'));
assert.ok(main.includes('ALPHA 5.8.2 · COMBAT CONTROL'));
assert.ok(loader.includes('retargetClip(targetMesh,fbx,clip'));
assert.ok(loader.includes("if(!m || m[2]!=='quaternion')continue"));
assert.ok(loader.includes('actionClip.blendMode=THREE.AdditiveAnimationBlendMode'));
assert.ok(loader.includes('safeCombatBone581(m[1])'));
assert.ok(loader.includes('invFirst.clone().multiply(current)'));
assert.ok(!loader.includes('fixedTracks.push(track)')); 
assert.ok(controller.includes('installCombatAnimations(newClips)'));
assert.ok(controller.includes("playCombatAction('Combo'+comboIndex"));
assert.ok(controller.includes("playCombatAction('Block'"));
assert.ok(controller.includes("playCombatAction('Impact'"));
assert.ok(main.includes('rodin54?.triggerSpecial(i)'));
console.log('PASS: 7 original FBX animation clips, correct bone namespaces, Rodin retarget wiring and safe fallback');
