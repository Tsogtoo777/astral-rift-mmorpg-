import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {GRAPHICS_PRESETS_6210,normalizeGraphicsMode6210,renderRatio6210,adjustedAutoRatio6210,installGraphics6210} from '../src/graphics6210.js';
const main=readFileSync('src/main.js','utf8');
const old=readFileSync('src/alpha40.js','utf8');
const fx=readFileSync('src/advanced50.js','utf8');
assert.equal(Object.keys(GRAPHICS_PRESETS_6210).length,5);
assert.equal(normalizeGraphicsMode6210('random'),'auto');
assert.equal(normalizeGraphicsMode6210('sharp'),'sharp');
assert.equal(renderRatio6210(1.8,900,400),1.8);
assert.ok(renderRatio6210(2.2,2300,1100)<1.3,'Pixel budget should protect big viewports');
assert.equal(renderRatio6210(.2,900,400),.75);
assert.equal(adjustedAutoRatio6210(1.7,29),1.55);
assert.equal(adjustedAutoRatio6210(1.2,59,2),1.3);
assert.equal(adjustedAutoRatio6210(1.2,45,5),1.2);
assert.ok(main.includes('graphics6210.update(now)'));
assert.ok(main.includes('graphics6210.mountSettings()'));
assert.ok(main.includes('graphicsManaged:true'));
assert.ok(old.includes('if(!api.graphicsManaged&&qualityClock>6)'));
assert.ok(!fx.includes('renderer.setPixelRatio'),'Advanced FX must not override graphics settings');
assert.equal(JSON.parse(readFileSync('package.json','utf8')).version,'6.2.10-alpha');
// Renderer stub allows verifying UI changes without WebGL or browser.
const events=[]; const storage=new Map();
const prevWindow=globalThis.window;
globalThis.window={innerWidth:900,innerHeight:400,localStorage:{getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)},addEventListener:(name,fn)=>events.push([name,fn])};
const ratios=[];
const controller=installGraphics6210({renderer:{setPixelRatio:r=>ratios.push(r)}});
assert.equal(controller.getRatio(),1.7);
controller.setMode('ultra');assert.equal(controller.getRatio(),2.2);
controller.setMode('smooth');assert.equal(controller.getRatio(),1);
controller.setMode('sharp');assert.equal(controller.getRatio(),1.8);
assert.equal(storage.get('astralRiftGraphics6210'),'sharp');
controller.setMode('auto');assert.equal(controller.getRatio(),1.7);
for(let t=100;t<11000;t+=80)controller.update(t);
assert.ok(controller.getRatio()<1.7,'Low FPS must reduce AUTO ratio');
