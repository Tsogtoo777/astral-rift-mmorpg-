import assert from 'node:assert/strict';
import fs from 'node:fs';
import {EQUIPMENT_59,SLOTS_59,createEquipment59} from '../src/equipment59.js';
const gear=createEquipment59();
assert.equal(EQUIPMENT_59.length,10);
assert.equal(SLOTS_59.length,8);
assert.equal(gear.get('weapon').id,'iron-longsword');
assert.equal(gear.get('chest').id,'wanderer-coat');
assert.equal(gear.bonuses().attack,4);
assert.equal(gear.bonuses().defense,14);
assert.equal(gear.bonuses().hp,20);
assert.equal(gear.bonuses().stamina,10);
assert.equal(gear.buy('wanderer-greatsword',200).ok,false);
assert.equal(gear.buy('wanderer-greatsword',500).price,400);
assert.equal(gear.buy('wanderer-greatsword',500).ok,false,'cannot double purchase');
assert.equal(gear.equip('wanderer-greatsword'),true);
assert.equal(gear.get('weapon').visual,'great');
assert.equal(gear.bonuses().attack,16);
assert.equal(gear.unequip('chest'),true);
assert.equal(gear.bonuses().hp,8);
assert.equal(gear.unequip('weapon'),false,'cannot remove weapon when combat assumes active sword');
const fromSave=createEquipment59(gear.snapshot());
assert.equal(fromSave.get('weapon').id,'wanderer-greatsword');
assert.equal(fromSave.get('chest'),null);
assert.equal(fromSave.equip('dark-katana'),false,'not owned');
const hacked=createEquipment59({owned:['INVALID','dark-katana'],equipped:{head:'dark-katana',weapon:'dark-katana'}});
assert.equal(hacked.get('head'),null);
assert.equal(hacked.get('weapon').id,'dark-katana');
const html=fromSave.render(830);
assert(html.includes('data-equip59'));
assert(html.includes('data-buy59'));
assert(html.includes('data-unequip59'));
const main=fs.readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
const rig=fs.readFileSync(new URL('../src/meshy597.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('../src/style.css',import.meta.url),'utf8');
assert(main.includes('equipment59:equipment59.snapshot()'),'save persists equipment');
assert(main.includes('finishEquipment59(oldHp)'),'gear changes update hp/visual');
assert(main.includes('raw-armorRank18*2-equipment59.bonuses().defense'),'defense used by enemy hit');
assert(main.includes('swordRank18*5+talents19[0]*4+equipment59.bonuses().attack'),'weapon attack bonus in sword hit');
assert(main.includes('100+equipment59.bonuses().stamina'),'stamina max linked to gear');
assert(main.includes('equip23.onclick=showEquipment59'),'legacy equipment screen integrated');
assert(rig.includes('setSwordStyle'),'sword variants wired');
assert(css.includes('.eq59-slots'),'mobile equipment layout');
