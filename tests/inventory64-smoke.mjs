import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {inventoryCards64,inventoryHtml64} from '../src/inventory64.js';
const data={gold:80,potions:2,ore:3,crystal:1,loot:{fang:5,insignia:2,shadow:1},inventory:['Ойн сахиус','<img src=x onerror=alert(1)>'],owned:['dark-katana'],equipped:{weapon:'dark-katana'}};
const cards=inventoryCards64(data);
assert.equal(cards.find(x=>x.id==='fang').count,5);
assert.equal(cards.find(x=>x.id==='dark-katana').equipped,true);
assert.equal(cards.find(x=>x.id==='potion').count,2);
assert.equal(cards.find(x=>x.id==='alloy'),undefined);
const html=inventoryHtml64(data);
assert.ok(html.includes('data-item64='));
assert.ok(html.includes('data-filter64="equipment"'));
assert.ok(html.includes('data-filter64="material"'));
assert.ok(html.includes('id="ar64-search"'));
assert.ok(html.includes('data-category64="equipment"'));
assert.ok(html.includes('data-category64="material"'));
assert.ok(cards.some(x=>x.id==='potion'&&x.category==='consumable'));
assert.ok(html.includes('80 алт'));
assert.ok(html.includes('Өмссөн'));
assert.ok(!html.includes('<img src=x'));
assert.ok(html.includes('&lt;img'));
const main=readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
assert.ok(main.includes("import {inventoryHtml64,bindInventory64} from './inventory64.js'"));
assert.ok(main.includes('bindInventory64(win,bag64)'));
for(const id of ['forgeFromBag18','usePotion16','swapWeapon16','openEquipment59'])assert.ok(main.includes(id));
console.log('PASS Alpha 6.4 inventory: grid, counts, equipped gear, legacy save, HTML escaping, existing actions');

const src=readFileSync(new URL('../src/inventory64.js',import.meta.url),'utf8');
assert.ok(src.includes('data-bag-action64'));
assert.ok(src.includes("action==='use-potion'"));
assert.ok(main.includes("equipment59.equip(id)"));
assert.ok(main.includes("equipment59.unequip(slot)"));
